def info_cells(pt, idx, za, m):
    z = per_inst(pt, m)
    if z is None: return D, ""
    z = z[idx]; dd = z - za; hw = stats.t.ppf(0.975, len(dd) - 1) * dd.std(ddof=1) / math.sqrt(len(dd)) if len(dd) > 1 else float("nan")
    return f"{dd.mean() / za.mean() * 100:.2f}", (f"[{(dd.mean() - hw) / za.mean() * 100:.1f}, {(dd.mean() + hw) / za.mean() * 100:.1f}]" if hw == hw else "")
col = {}
for pt in MAIN:
    za, ntot = ao_exact(pt); zr = per_inst(pt, "RollDP")
    if za is None or zr is None or len(za) == 0: col[pt] = None; continue
    idx = za.index.intersection(zr.index); za, zr_ = za[idx], zr[idx]; c = {"n": f"{len(idx)}/{ntot}", "Zao": f"{za.mean():.1f}"}
    dF = sub(pt, "PI-FREE"); dF = dF[dF.instance.isin(idx)]
    if len(dF) and dF.groupby("instance").size().min() == 3 and set(dF.instance) >= set(idx):
        dF = dF.assign(LB=np.maximum(xval(dF, "bound").values, xval(dF, "nowait_lb").values))
        zf, zl = dF.groupby("instance").Z.mean()[idx], dF.groupby("instance").LB.mean()[idx]
        lo, hi = (za.mean() - zf.mean()) / za.mean() * 100, (za.mean() - zl.mean()) / za.mean() * 100
        c["ao"] = (f"{lo:.2f}" if abs(hi - lo) < 0.005 else f"[{lo:.2f}, {hi:.2f}]"); c["ao2"] = f"({int(dF.status.eq('OPTIMAL').sum())}/{len(dF)} proven)"
    else: c["ao"], c["ao2"] = D, ""
    for m, _ in INFO: c["i" + m] = info_cells(pt, idx, za, m)
    for m, _ in POLD: c["p" + m] = gap_cell(per_inst(pt, m), zr_)
    col[pt] = c
