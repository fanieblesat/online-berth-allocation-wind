def sub(pt, m): return df[(df.point == pt) & (df.method == m)]
def per_inst(pt, m):
    d = sub(pt, m)
    return d.groupby("instance").Z.mean() if len(d) else None
def xval(d, key):
    return d.extra.fillna("").astype(str).str.extract(key + r"=([-0-9.eE+naninf]+)")[0].astype(float)
def tost(x, y, frac=0.01):
    d = (x - y).values; n = len(d); mar = frac * float(y.mean())
    if n < 3 or d.std(ddof=1) == 0: return False
    se = d.std(ddof=1) / math.sqrt(n)
    return (1 - stats.t.cdf((d.mean() + mar) / se, n - 1)) < .05 and stats.t.cdf((d.mean() - mar) / se, n - 1) < .05
def fp(p):
    if p != p: return D
    if p >= 1e-3: return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e"); return f"${m}\\cdot10^{{{int(e)}}}$"
def sgn(g): return f"{g:+.2f}".replace("-", "$-$")
def gap_cell(zp, zr, test=True):
    if zp is None or zr is None: return D
    j = zp.index.intersection(zr.index)
    if len(j) == 0: return D
    g = (zp[j].mean() - zr[j].mean()) / zr[j].mean() * 100
    if not test: return sgn(g)
    p = stats.wilcoxon(zp[j], zr[j]).pvalue if len(j) >= 2 and not np.allclose(zp[j], zr[j]) else float("nan")
    return f"{sgn(g)} ({fp(p)}{', eq.' if tost(zp[j], zr[j]) else ''})"
def ao_exact(pt):
    d = sub(pt, "PI-AO")
    if d.empty: return None, 0
    ok = d.groupby("instance").status.apply(lambda s: (s == "optimal").all()); ok = ok[ok].index
    return d[d.instance.isin(ok)].groupby("instance").Z.mean(), d.instance.nunique()
def write(name, body):
    open(f"{a.out}/{name}.tex", "w").write("% generated by scripts/build_tables.py from the record -- do not edit by hand\n" + body)

