"""build_tables.py — writes every result table of the manuscript (overleaf/tables/*.tex) from the record:
results/runs.csv, results/exact.csv and results/train_curves.csv. Written before the campaign; runs on partial records
(missing cells are printed as '---', missing rows as 'pending').
Usage: python3 build_tables.py [--out ../overleaf/tables] [--results results]

Conventions (DESIGN.md §6, paper Sec. 6.2): per-instance values = mean over the 3 realizations (and over the 5 seeds
for DQN/QL); gaps in % of the reference's mean over the same instances; p = Wilcoxon signed-rank on the paired
per-instance means; 'eq.' = equivalent within +-1% of the reference mean (TOST, alpha = 0.05).
Decomposition: only instances whose PI-AO is optimal on all 3 realizations; Delta_AO is the interval
[Z*_AO - Z_FREE incumbent, Z*_AO - max(CP-SAT bound, no-wait bound)] in % of Z*_AO, with the number of proven FREE optima."""
